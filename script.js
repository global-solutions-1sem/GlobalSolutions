function mudarTema(tema){
    if(tema == "verde"){
        document.body.style.background =
        "linear-gradient(135deg,#0d3b0d,#1e7d32,#4caf50)";
}
    if(tema == "escuro"){
        document.body.style.background =
        "linear-gradient(135deg,#000,#111,#222)";
}
    if(tema == "padrao"){
        document.body.style.background =
        "linear-gradient(135deg,#12002f,#250062,#860063)"
    }   
}